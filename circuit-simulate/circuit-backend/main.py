@app.post("/simulate", response_model=SimulationResult)
async def simulate(req: SimulateRequest) -> Any:
    """
    Accepts the JSON netlist produced by the frontend, runs a DC
    operating-point simulation via ngspice, and returns branch currents
    (and node voltages) as scalar traces.

    For a resistive circuit the result is a single operating-point value,
    so each trace contains exactly one element.
    """
    # --- Build the SPICE deck ---
    spice = _build_spice_deck(req.netlist)
    print("\n=== SPICE deck ===")
    print(spice)
    print("==================\n")

    # --- Run ngspice ---
    try:
        raw_output = _run_ngspice(spice)
    except FileNotFoundError:
        raise HTTPException(
            status_code=500,
            detail=(
                f"ngspice not found at '{NGSPICE}'. "
                "Install ngspice and make sure it is on your PATH, "
                "or set the NGSPICE_PATH environment variable."
            ),
        )
    except subprocess.TimeoutExpired:
        raise HTTPException(status_code=500, detail="ngspice timed out.")

    print("=== ngspice raw output ===")
    print(raw_output)
    print("==========================\n")

    # --- Parse results ---
    op_values = _parse_op_output(raw_output)

    if not op_values:
        # ngspice ran but produced no parseable numbers → return the raw log
        return SimulationResult(
            ok=False,
            message=f"ngspice ran but no values were parsed.\n\nRaw output:\n{raw_output}",
        )

    # --- Console-log the current values (Amperes) as requested ---
    print("=== Branch currents (Amperes) ===")
    for label, value in op_values.items():
        if label.startswith("I("):
            print(f"  {label} = {value:.6e} A")
    print("=================================\n")

    # Wrap scalars in single-element lists so the frontend trace format is happy
    traces: dict[str, list[float]] = {k: [v] for k, v in op_values.items()}

    return SimulationResult(ok=True, traces=traces)


