class GenerateCircuitRequest(BaseModel):
    image: str                   # PNG/JPEG as base64 or a data: URL
    title: str = "drawn-circuit"


def _decode_request_image(req: GenerateCircuitRequest):
    import base64
    import binascii

    from recognizer import decode_image

    payload = req.image.split(",", 1)[1] if req.image.startswith("data:") else req.image
    try:
        data = base64.b64decode(payload, validate=True)
    except binascii.Error:
        raise HTTPException(status_code=400, detail="Image is not valid base64.")
    return decode_image(data)


@app.post("/detect-components")
def detect_components(req: GenerateCircuitRequest) -> dict[str, Any]:
    """
    Component detection only, for run-time processing while the user draws:
    returns each detected symbol's class, confidence and box (image pixels).
    """
    from recognizer import RecognitionError, detect_boxes

    image = _decode_request_image(req)
    try:
        boxes = detect_boxes(image)
    except RecognitionError as e:
        raise HTTPException(status_code=422, detail=str(e))
    h, w = image.shape[:2]
    return {
        "image_width": w,
        "image_height": h,
        "detections": [
            {"type": b.cls_name, "conf": round(b.conf, 3),
             "bbox": {"x1": b.x1, "y1": b.y1, "x2": b.x2, "y2": b.y2}}
            for b in boxes
        ],
    }


@app.post("/generate-circuit")
def generate_circuit(req: GenerateCircuitRequest) -> dict[str, Any]:
    """
    Accepts an image of a hand-drawn circuit (e.g. the frontend's drawing
    canvas), runs it through the circuitmodel pipeline, and returns the
    netlist JSON in the same format as circuitmodel's netlist.json.
    """
    from recognizer import RecognitionError, recognize

    image = _decode_request_image(req)
    try:
        return recognize(image, title=req.title)
    except RecognitionError as e:
        raise HTTPException(status_code=422, detail=str(e))


