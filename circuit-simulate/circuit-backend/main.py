"""
circuit-backend/main.py
========================
Single-route FastAPI server that accepts a resistive-circuit netlist,
writes a SPICE deck, runs it through ngspice, parses the output, and
returns branch currents (in Amperes).

Run:
    uvicorn main:app --reload --port 8000

Prerequisites:
    pip install fastapi uvicorn
    ngspice must be on PATH  (or set NGSPICE_PATH env var)
"""

import json
import os
import re
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

# ---------------------------------------------------------------------------
# App setup
# ---------------------------------------------------------------------------
app = FastAPI(title="Circuit Simulator Backend")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],          # tighten for production
    allow_methods=["POST", "GET"],
    allow_headers=["*"],
)

# ---------------------------------------------------------------------------
# Request / response models  (mirror src/api/simulate.ts)
# ---------------------------------------------------------------------------

class NetlistComponent(BaseModel):
    id: str
    ref: str
    type: str
    nodes: list[str]
    params: dict[str, float]


class Netlist(BaseModel):
    version: int
    components: list[NetlistComponent]
    nets: list[str]


class TransientConfig(BaseModel):
    stepSeconds: float
    stopSeconds: float


class AcConfig(BaseModel):
    startHz: float
    stopHz: float
    pointsPerDecade: int


class Analysis(BaseModel):
    mode: str                    # "dc" | "tran" | "ac"
    tran: TransientConfig | None = None
    ac: AcConfig | None = None


class SimulateRequest(BaseModel):
    netlist: Netlist
    analysis: Analysis


class SimulationResult(BaseModel):
    ok: bool
    message: str | None = None
    traces: dict[str, list[float]] | None = None

# ---------------------------------------------------------------------------
# SPICE deck builder   (resistive circuits → DC operating point)
# ---------------------------------------------------------------------------

_TYPE_TO_SPICE = {
    "resistor":   "R",
    "capacitor":  "C",
    "inductor":   "L",
    "vsource_dc": "V",
    "vsource_ac": "V",
    "battery":    "V",
    "vsource_dep": "V",   # control not captured: simulated at its set voltage
    "diode":      "D",
    "ground":     None,   # node marker only
}


def _build_spice_deck(netlist: Netlist) -> str:
    """Convert our JSON netlist to a SPICE deck string.

    For a purely resistive circuit we always run a DC operating-point (.op)
    so we get branch currents directly from ngspice.
    """
    lines: list[str] = ["* Auto-generated by circuit-backend"]

    voltage_sources: list[str] = []
    uses_diode = False

    for comp in netlist.components:
        prefix = _TYPE_TO_SPICE.get(comp.type)
        if prefix is None:
            continue

        nodes = " ".join(comp.nodes)

        if comp.type == "resistor":
            r = comp.params.get("resistance", 1000)
            lines.append(f"R{comp.ref.lstrip('R')} {nodes} {r}")

        elif comp.type == "capacitor":
            c = comp.params.get("capacitance", 1e-6)
            lines.append(f"C{comp.ref.lstrip('C')} {nodes} {c}")

        elif comp.type == "inductor":
            l = comp.params.get("inductance", 1e-3)
            lines.append(f"L{comp.ref.lstrip('L')} {nodes} {l}")

        elif comp.type == "vsource_dc":
            v = comp.params.get("voltage", 5)
            lines.append(f"V{comp.ref.lstrip('V')} {nodes} DC {v}")
            voltage_sources.append(comp.ref)

        elif comp.type in ("battery", "vsource_dep"):
            v = comp.params.get("voltage", 5)
            name = comp.ref if comp.ref.startswith("V") else f"V{comp.ref}"
            lines.append(f"{name} {nodes} DC {v}")
            voltage_sources.append(name)

        elif comp.type == "diode":
            lines.append(f"D{comp.ref.lstrip('D')} {nodes} DMOD")
            uses_diode = True

        elif comp.type == "vsource_ac":
            v = comp.params.get("voltage", 1)
            freq = comp.params.get("frequency", 50)
            lines.append(f"V{comp.ref.lstrip('V')} {nodes} AC {v} SIN(0 {v} {freq})")
            voltage_sources.append(comp.ref)

    if uses_diode:
        # 1N4148-like small-signal diode
        lines.append(".model DMOD D(IS=2.52n RS=0.568 N=1.752)")

    # DC operating point — gives I(Vx) for every voltage source
    lines.append(".op")
    lines.append(".end")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# ngspice runner
# ---------------------------------------------------------------------------

NGSPICE = os.environ.get("NGSPICE_PATH", "ngspice")


def _run_ngspice(spice_deck: str) -> str:
    """Write a temp .cir file, run ngspice, return stdout."""
    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".cir", delete=False, encoding="utf-8"
    ) as f:
        f.write(spice_deck)
        cir_path = f.name

    try:
        result = subprocess.run(
            [NGSPICE, "-b", cir_path],        # -b = batch mode (no GUI)
            capture_output=True,
            text=True,
            timeout=30,
        )
        output = result.stdout + result.stderr
        return output
    finally:
        Path(cir_path).unlink(missing_ok=True)


# ---------------------------------------------------------------------------
# Output parser
# ---------------------------------------------------------------------------

_CURRENT_RE = re.compile(
    r"i\(v(\w+)\)\s*=\s*([-+]?\d*\.?\d+(?:[eE][-+]?\d+)?)",
    re.IGNORECASE,
)

_NODE_VOLTAGE_RE = re.compile(
    r"v\((\w+)\)\s*=\s*([-+]?\d*\.?\d+(?:[eE][-+]?\d+)?)",
    re.IGNORECASE,
)


def _parse_op_output(raw: str) -> dict[str, float]:
    """Extract DC operating-point values from ngspice -b output."""
    results: dict[str, float] = {}

    for m in _CURRENT_RE.finditer(raw):
        label = f"I(V{m.group(1).upper()})"
        value = float(m.group(2))
        results[label] = value

    for m in _NODE_VOLTAGE_RE.finditer(raw):
        label = f"V({m.group(1)})"
        value = float(m.group(2))
        results[label] = value

    return results


